// maxSchemaErrorRunes bounds a settings declaration error shown in the admin.
const maxSchemaErrorRunes = 300

// ThemeSettings displays the settings page for a specific theme.
//
// A theme with its own settings template (templates/admin/theme_settings.tmpl)
// renders it inside the admin layout. A theme that only declares [[settings]]
// in theme.toml gets a form generated by core from the declaration, so it
// never runs theme markup in the admin.
func (h *Handler) ThemeSettings(c *gin.Context) {
	if !h.checkPermission(c, "setting", "read") {
		return
	}
	slug := c.Param("slug")
	lang := h.svc.AdminLanguage()
	redirectError := func(message string) {
		c.Redirect(http.StatusFound, "/admin/themes?error="+url.QueryEscape(message))
	}

	// Find theme display info
	var themeName string
	if h.themeManager != nil {
		for _, t := range h.themeManager.Available() {
			if t.Slug == slug {
				themeName = t.Name
				break
			}
		}
	}
	if themeName == "" {
		redirectError(adminT(lang, "error.theme_not_found"))
		return
	}

	schema, schemaErr := h.themeSettingsSchema(slug)
	if schemaErr != nil {
		log.Printf("Theme settings declaration invalid (%s): %v", slug, schemaErr)
		redirectError(adminT(lang, "error.theme_settings_schema_invalid", truncateRunes(schemaErr.Error(), maxSchemaErrorRunes)))
		return
	}

	// Locate the theme settings template
	settingsTmpl := h.themeManager.SettingsTemplate(slug)
	if !settingsTmpl.Valid() {
		if schema == nil {
			redirectError(adminT(lang, "error.theme_settings_unavailable"))
			return
		}
		h.renderThemeSettingsForm(c, slug, themeName, schema)
		return
	}

	// Compile the theme settings template with admin layout
	tmpl, err := h.parseWithAdminLayout(settingsTmpl)
	if err != nil {
		log.Printf("Theme settings template error (%s): %v", slug, err)
		redirectError(adminT(lang, "error.theme_template_failed"))
		return
	}

	colorScheme := h.svc.GetOption("theme_color_scheme")
	if colorScheme == "" {
		colorScheme = "orange"
	}

	data := gin.H{
		"Title":            adminT(lang, "title.theme_settings", themeName),
		"Active":           "themes",
		"ThemeName":        themeName,
		"ThemeSlug":        slug,
		"ColorScheme":      colorScheme,
		"Settings":         h.svc.GetAllOptions(),
		"ExtensionCatalog": h.themeCatalog(slug),
	}

	data["AdminLanguage"] = lang
	data["CurrentUser"] = c.GetString("admin_username")
	data["CurrentRole"] = c.GetString("admin_role")
	data["MenuItems"] = h.buildMenuItems(lang, c.GetString("admin_role"))
	data["SiteName"] = h.svc.SiteName()
	data["PublicBaseURL"] = requestBaseURL(c)
	h.injectVersionStatus(data)
	h.injectExtensionBanners(c, data)

	if success := c.Query("success"); success != "" {
		data["Success"] = success
	}
	if errMsg := c.Query("error"); errMsg != "" {
		data["Error"] = errMsg
	}

	c.Header("Content-Type", "text/html; charset=utf-8")
	if err := tmpl.ExecuteTemplate(c.Writer, "admin", data); err != nil {
		log.Printf("Theme settings render error (%s): %v", slug, err)
		c.String(http.StatusInternalServerError, "Template error")
	}
}

// ThemeSettingsSave saves theme-specific settings.
//
// A theme that declares [[settings]] may only save declared keys: an
// undeclared key rejects the whole form, and every value is checked against
// its declared type. Other themes use the legacy prefix rules.
//
// Theme forms may also edit core-owned keys (for example site_name). Those
// keys keep the system settings page's rules — read-only keys are rejected,
// values are validated, and site_icon regenerates the favicon — no matter which
// form submits them. All accepted values are written in one transaction so a
// failure never reports success or leaves a partial save.
func (h *Handler) ThemeSettingsSave(c *gin.Context) {
	if !h.checkPermission(c, "setting", "update") {
		return
	}
	slug := c.Param("slug")
	lang := h.svc.AdminLanguage()
	settingsURL := "/admin/themes/" + url.PathEscape(slug) + "/settings"
	fail := func(message string) {
		c.Redirect(http.StatusFound, settingsURL+"?error="+url.QueryEscape(message))
	}

	schema, err := h.themeSettingsSchema(slug)
	if err != nil {
		fail(adminT(lang, "error.theme_settings_schema_invalid", truncateRunes(err.Error(), maxSchemaErrorRunes)))
		return
	}
	if c.Request.Form == nil {
		_ = c.Request.ParseForm()
	}

	values := make(map[string]string)
	// Save color scheme. Core does not know which palette names a theme defines,
	// so we only sanity-check the shape (CSS-class-safe token) and let the theme
	// own the list of valid values.
	if cs := c.PostForm("color_scheme"); isSafeSchemeToken(cs) {
		values["theme_color_scheme"] = cs
	}
	if schema != nil {
		err = h.declaredThemeSettingValues(c, slug, schema, values)
	} else {
		// LEGACY(theme-setting-prefixes): see legacyThemeSettingValues.
		err = h.legacyThemeSettingValues(c, slug, values)
	}
	if err != nil {
		fail(err.Error())
		return
	}
	if icon, ok := values["site_icon"]; ok && icon != h.svc.options.Get("site_icon") {
		if err := h.svc.SyncSiteIcon(icon); err != nil {
			fail(err.Error())
			return
		}
	}
	if err := h.svc.UpdateSettings(values); err != nil {
		fail(adminT(lang, "error.update_failed", err.Error()))
		return
	}

	h.invalidatePageCache()
	h.fireOptionsBulkUpdated(c)
	h.logAction(c, "update", "theme_settings", 0, "theme settings updated")
	c.Redirect(http.StatusFound, settingsURL+"?success="+url.QueryEscape(adminT(lang, "notice.theme_settings_saved")))
}

// themeSettingsSchema returns the theme's settings declaration, or nil when
// no theme manager is wired.
func (h *Handler) themeSettingsSchema(slug string) (*coreTheme.SettingsSchema, error) {
	if h.themeManager == nil {
		return nil, nil
	}
	return h.themeManager.SettingsSchema(slug)
}

// declaredThemeSettingValues adds the submitted values of a theme that
// declares its settings. Undeclared keys and invalid values reject the whole
// submission; the error lists every problem.
func (h *Handler) declaredThemeSettingValues(c *gin.Context, slug string, schema *coreTheme.SettingsSchema, values map[string]string) error {
	lang := h.svc.AdminLanguage()
	catalog := h.themeCatalog(slug)
	var unknown, problems []string
	keys := make([]string, 0, len(c.Request.PostForm))
	for key := range c.Request.PostForm {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		formValues := c.Request.PostForm[key]
		if key == "color_scheme" || len(formValues) == 0 {
			continue
		}
		field, ok := schema.Field(key)
		if !ok {
			unknown = append(unknown, key)
			continue
		}
		value, err := field.Validate(formValues[0])
		if err != nil {
			var valueErr *coreTheme.SettingValueError
			reason := err.Error()
			if errors.As(err, &valueErr) {
				reason = settingErrorText(lang, field, valueErr.Reason)
			}
			problems = append(problems, settingText(catalog, lang, field.LabelKey, field.Label, field.N)+": "+reason)
			continue
		}
		if err := h.validateSystemSettingValue(key, value, lang); err != nil {
			problems = append(problems, settingText(catalog, lang, field.LabelKey, field.Label, field.N)+": "+err.Error())
			continue
		}
		values[key] = value
	}
	if len(unknown) > 0 {
		return errors.New(adminT(lang, "error.theme_settings_unknown", strings.Join(unknown, ", ")))
	}
	if len(problems) > 0 {
		return errors.New(adminT(lang, "error.theme_settings_invalid", strings.Join(problems, "; ")))
	}
	return nil
}

// legacyThemeSettingPrefixes are the key prefixes accepted from themes that
// do not declare [[settings]].
var legacyThemeSettingPrefixes = []string{"home_", "about_", "company_", "social_", "footer_", "showcase_", "site_", "nav_", "contact_", "package_"}

// legacyNotedThemes records the themes already logged as using the legacy
// rules, so each is logged once per process.
var legacyNotedThemes sync.Map

// legacyThemeSettingValues adds the submitted values of a theme without a
// settings declaration.
//
// LEGACY(theme-setting-prefixes): themes that predate [[settings]] (core
// 0.7.20) save every submitted key that is registered as translatable or
// starts with one of legacyThemeSettingPrefixes; other keys are dropped
// silently. These prefixes are theme naming conventions hard-coded in core,
// which is why declared settings replace them (audit A19).
//   - Why it stays: every theme built before 0.7.20, public and private,
//     relies on it; a theme without a declaration would otherwise lose all of
//     its settings.
//   - Timing: it runs per request, only for themes without [[settings]].
//   - Removal: once every public and private theme declares [[settings]] and
//     at least one release has shipped with them. Remove this function, its
//     call site, legacyThemeSettingPrefixes and their tests, and note in the
//     release notes that themes must declare their settings.
func (h *Handler) legacyThemeSettingValues(c *gin.Context, slug string, values map[string]string) error {
	if _, noted := legacyNotedThemes.LoadOrStore(slug, true); !noted {
		log.Printf("Theme %q has no [[settings]] declaration; saving its settings with the legacy prefix rules", slug)
	}
	lang := h.svc.AdminLanguage()
	for key, formValues := range c.Request.PostForm {
		if len(formValues) == 0 {
			continue
		}
		if !option.IsTranslatable(key) && !hasAnyPrefix(key, legacyThemeSettingPrefixes) {
			continue
		}
		if err := h.validateSystemSettingValue(key, formValues[0], lang); err != nil {
			return err
		}
		values[key] = formValues[0]
	}
	return nil
}

// hasAnyPrefix reports whether s has any of the given prefixes.
func hasAnyPrefix(s string, prefixes []string) bool {
	for _, p := range prefixes {
		if strings.HasPrefix(s, p) {
			return true
		}
	}
	return false
}

// settingText returns the theme's translation of key for the admin language,
// or fallback. "{n}" in a translated message is replaced by n for repeated
// settings; fallback texts arrive with it already replaced.
func settingText(catalog *coreI18n.Catalog, lang, key, fallback string, n int) string {
	if key != "" {
		if msg := catalog.Message(lang, key); msg != "" {
			if n > 0 {
				msg = strings.ReplaceAll(msg, "{n}", strconv.Itoa(n))
			}
			return msg
		}
	}
	return fallback
}

// settingErrorText describes a SettingValueError reason in the admin language.
func settingErrorText(lang string, field coreTheme.SettingField, reason string) string {
	switch reason {
	case coreTheme.SettingErrTooLong:
		return adminT(lang, "error.setting_too_long", field.MaxLength)
	case coreTheme.SettingErrOutOfRange:
		switch {
		case field.Min != nil && field.Max != nil:
			return adminT(lang, "error.setting_out_of_range", strconv.Itoa(*field.Min), strconv.Itoa(*field.Max))
		case field.Min != nil:
			return adminT(lang, "error.setting_below_min", strconv.Itoa(*field.Min))
		default:
			return adminT(lang, "error.setting_above_max", strconv.Itoa(*field.Max))
		}
	default:
		return adminT(lang, "error.setting_"+reason)
	}
}

// themeSettingsFormGroup is one section of a generated theme settings form.
type themeSettingsFormGroup struct {
	Title  string
	Fields []themeSettingsFormField
}

// themeSettingsFormField is one control of a generated theme settings form.
type themeSettingsFormField struct {
	Key       string
	ID        string
	Type      string
	InputType string // HTML input type for single-line controls
	Label     string
	Help      string
	Value     string
	Checked   bool
	Required  bool
	Min       string
	Max       string
	MaxLength int
	Wide      bool
	Options   []SettingOptionView
}

// renderThemeSettingsForm renders the core-generated settings form of a
// theme that declares [[settings]]. Unsaved settings show their defaults.
func (h *Handler) renderThemeSettingsForm(c *gin.Context, slug, themeName string, schema *coreTheme.SettingsSchema) {
	lang := h.svc.AdminLanguage()
	catalog := h.themeCatalog(slug)
	saved := h.svc.GetAllOptions()

	byGroup := map[string][]themeSettingsFormField{}
	hasRequired := false
	for _, field := range schema.Fields {
		hasRequired = hasRequired || (field.Required && field.Type != coreTheme.SettingBool)
		value, ok := saved[field.Key]
		if !ok {
			value = field.Default
		}
		view := themeSettingsFormField{
			Key:       field.Key,
			ID:        "ts-" + field.Key,
			Type:      field.Type,
			InputType: "text",
			Label:     settingText(catalog, lang, field.LabelKey, field.Label, field.N),
			Help:      settingText(catalog, lang, field.HelpKey, field.Help, field.N),
			Value:     value,
			Required:  field.Required,
			MaxLength: field.MaxLength,
			Wide:      field.Type == coreTheme.SettingText,
		}
		switch field.Type {
		case coreTheme.SettingBool:
			view.Checked = value == "1"
		case coreTheme.SettingInt:
			view.InputType = "number"
			if field.Min != nil {
				view.Min = strconv.Itoa(*field.Min)
			}
			if field.Max != nil {
				view.Max = strconv.Itoa(*field.Max)
			}
		case coreTheme.SettingURL:
			view.InputType = "url"
		case coreTheme.SettingEmail:
			view.InputType = "email"
		case coreTheme.SettingSelect:
			for _, opt := range field.Options {
				view.Options = append(view.Options, SettingOptionView{
					Value: opt.Value,
					Label: settingText(catalog, lang, opt.LabelKey, firstNonEmpty(opt.Label, opt.Value), field.N),
				})
			}
		}
		byGroup[field.Group] = append(byGroup[field.Group], view)
	}

	var groups []themeSettingsFormGroup
	for _, group := range schema.Groups {
		if fields := byGroup[group.Key]; len(fields) > 0 {
			title := settingText(catalog, lang, group.LabelKey, firstNonEmpty(group.Label, group.Key), 0)
			groups = append(groups, themeSettingsFormGroup{Title: title, Fields: fields})
		}
	}
	if fields := byGroup[""]; len(fields) > 0 {
		title := adminT(lang, "theme.settings_section_general")
		if len(groups) > 0 {
			title = adminT(lang, "theme.settings_section_other")
		}
		groups = append(groups, themeSettingsFormGroup{Title: title, Fields: fields})
	}

	h.render(c, "theme_settings_form", gin.H{
		"Title":       adminT(lang, "title.theme_settings", themeName),
		"Active":      "themes",
		"ThemeName":   themeName,
		"ThemeSlug":   slug,
		"Groups":      groups,
		"HasRequired": hasRequired,
	})
}

func firstNonEmpty(values ...string) string {
	for _, v := range values {
		if strings.TrimSpace(v) != "" {
			return v
		}
	}
	return ""
}
